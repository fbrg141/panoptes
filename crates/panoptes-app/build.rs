//! Generates the design system's icons and the loop mark as SVG files from
//! `packages/design-system/src/index.js`, so the icon set stays the design
//! tool's export and is never copied by hand.

use std::fmt::Write as _;
use std::path::PathBuf;

use serde_json::Value;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let source = manifest.join("../../packages/design-system/src/index.js");
    println!("cargo:rerun-if-changed={}", source.display());
    let js = std::fs::read_to_string(&source).expect("read the design system bundle");

    let mut out = String::from("// Generated by build.rs from the design system bundle.\n");
    out.push_str("pub static ICONS: &[(&str, &str)] = &[\n");
    for (name, nodes) in icons(&js) {
        let svg = icon_svg(&nodes);
        writeln!(out, "    ({name:?}, {svg:?}),").unwrap();
    }
    out.push_str("];\n");

    let geo = object_after(&js, "var GEO = ");
    out.push_str("pub static LOOP_MARKS: &[(&str, LoopGeometry)] = &[\n");
    for (size, g) in geo.as_object().unwrap() {
        let b: Vec<f64> = g["bounds"]
            .as_array()
            .unwrap()
            .iter()
            .map(|v| v.as_f64().unwrap())
            .collect();
        let pad = 6.0;
        let view = [b[0] - pad, b[1] - pad, b[2] - b[0] + pad * 2.0, b[3] - b[1] + pad * 2.0];
        let vb = format!("{} {} {} {}", view[0], view[1], view[2], view[3]);
        let path = |d: &str| {
            format!(
                r#"<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}"><path d="{d}" fill="black" fill-rule="evenodd"/></svg>"#
            )
        };
        let body = path(g["body"].as_str().unwrap());
        let pupils = path(g["pupils"].as_str().unwrap());
        writeln!(
            out,
            "    ({size:?}, LoopGeometry {{ body: {body:?}, pupils: {pupils:?}, aspect: {} }}),",
            view[3] / view[2]
        )
        .unwrap();
    }
    out.push_str("];\n");

    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("design_assets.rs");
    std::fs::write(dest, out).unwrap();
}

/// The icon table: `var ICONS = Object.assign({...}, {...});`.
fn icons(js: &str) -> Vec<(String, Vec<Value>)> {
    let start = js.find("var ICONS = Object.assign(").expect("ICONS in the bundle")
        + "var ICONS = Object.assign(".len();
    let mut rest = &js[start..];
    let mut icons = Vec::new();
    loop {
        let mut stream = serde_json::Deserializer::from_str(rest).into_iter::<Value>();
        let object = stream.next().unwrap().expect("an icon object");
        for (name, nodes) in object.as_object().unwrap() {
            icons.push((name.clone(), nodes.as_array().unwrap().clone()));
        }
        rest = rest[stream.byte_offset()..].trim_start();
        match rest.strip_prefix(',') {
            Some(next) => rest = next.trim_start(),
            None => break,
        }
    }
    icons
}

fn object_after(js: &str, marker: &str) -> Value {
    let start = js.find(marker).expect("marker in the bundle") + marker.len();
    serde_json::Deserializer::from_str(&js[start..])
        .into_iter::<Value>()
        .next()
        .unwrap()
        .unwrap()
}

/// A Lucide icon at a 1.5px stroke. GPUI paints an SVG as a mask in the
/// element's text colour, so the colour here only needs to be opaque.
fn icon_svg(nodes: &[Value]) -> String {
    let mut svg = String::from(
        r#"<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="black" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">"#,
    );
    for node in nodes {
        let tag = node[0].as_str().unwrap();
        write!(svg, "<{tag}").unwrap();
        for (key, value) in node[1].as_object().unwrap() {
            let value = match value {
                Value::String(s) => s.replace("currentColor", "black"),
                other => other.to_string(),
            };
            write!(svg, r#" {}="{}""#, attribute(key), value).unwrap();
        }
        svg.push_str("/>");
    }
    svg.push_str("</svg>");
    svg
}

/// React's camelCase SVG props as attributes.
fn attribute(key: &str) -> String {
    let mut out = String::new();
    for c in key.chars() {
        if c.is_ascii_uppercase() {
            out.push('-');
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}
